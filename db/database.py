
"""
WildGuard database access layer.
Uses SQLite locally and PostgreSQL when DATABASE_URL is configured.
Existing detection records are preserved during database initialization.
"""

import os
import sqlite3
import json
from datetime import datetime, timedelta
import random
from contextlib import contextmanager


BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB_PATH = os.path.join(BASE_DIR, "db", "detections.db")
SCHEMA_PATH = os.path.join(BASE_DIR, "db", "schema.sql")


def is_postgres(db_path=None):
    """Use PostgreSQL when DATABASE_URL is set, unless a SQLite path is given."""
    return bool(os.environ.get("DATABASE_URL")) and db_path is None


def get_db(db_path=None):
    """Connect to PostgreSQL on Render or SQLite locally."""
    if is_postgres(db_path):
        import psycopg2
        from psycopg2.extras import RealDictCursor

        url = os.environ["DATABASE_URL"]

        if url.startswith("postgres://"):
            url = url.replace("postgres://", "postgresql://", 1)

        return psycopg2.connect(url, cursor_factory=RealDictCursor)

    target_path = db_path or DB_PATH
    os.makedirs(os.path.dirname(os.path.abspath(target_path)), exist_ok=True)

    conn = sqlite3.connect(target_path)
    conn.row_factory = sqlite3.Row
    return conn


@contextmanager
def db_cursor(conn):
    """Manage cursors safely for both SQLite and PostgreSQL."""
    cur = conn.cursor()
    try:
        yield cur
    finally:
        cur.close()


def init_db(db_path=None):
    """Create missing tables and indexes without clearing existing records."""
    conn = get_db(db_path)

    try:
        if is_postgres(db_path):
            with db_cursor(conn) as cur:
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS detections (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        animal TEXT NOT NULL,
                        confidence DOUBLE PRECISION NOT NULL,
                        est_damage DOUBLE PRECISION NOT NULL DEFAULT 0.0,
                        source TEXT NOT NULL,
                        date TEXT NOT NULL,
                        time TEXT NOT NULL,
                        timestamp TEXT NOT NULL,
                        thumbnail_path TEXT,
                        box_coords TEXT
                    )
                """)

                cur.execute("""
                    CREATE INDEX IF NOT EXISTS idx_detections_animal
                    ON detections(animal)
                """)

                cur.execute("""
                    CREATE INDEX IF NOT EXISTS idx_detections_date
                    ON detections(date)
                """)

                cur.execute("""
                    CREATE INDEX IF NOT EXISTS idx_detections_timestamp
                    ON detections(timestamp)
                """)

            conn.commit()

        else:
            with open(SCHEMA_PATH, "r", encoding="utf-8") as file:
                conn.executescript(file.read())
            conn.commit()

    finally:
        conn.close()


def insert_detection(
    animal: str,
    confidence: float,
    est_damage: float,
    source: str,
    thumbnail_path: str = None,
    box_coords: list = None,
    custom_timestamp: datetime = None,
) -> int:
    """Insert one detection and return its database ID."""
    now = custom_timestamp or datetime.now()

    values = (
        animal.capitalize(),
        round(float(confidence), 3),
        round(float(est_damage), 2),
        source,
        now.strftime("%Y-%m-%d"),
        now.strftime("%H:%M:%S"),
        now.isoformat(timespec="seconds"),
        thumbnail_path,
        json.dumps(box_coords) if box_coords else None,
    )

    conn = get_db()

    try:
        with db_cursor(conn) as cur:
            if is_postgres():
                cur.execute("""
                    INSERT INTO detections (
                        animal, confidence, est_damage, source, date, time,
                        timestamp, thumbnail_path, box_coords
                    )
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
                    RETURNING id
                """, values)

                row_id = cur.fetchone()["id"]

            else:
                cur.execute("""
                    INSERT INTO detections (
                        animal, confidence, est_damage, source, date, time,
                        timestamp, thumbnail_path, box_coords
                    )
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, values)

                row_id = cur.lastrowid

        conn.commit()
        return row_id

    finally:
        conn.close()


def get_detections(
    limit: int = 100,
    animal_filter: str = None,
    source_filter: str = None,
) -> list:
    """Return newest detections, optionally filtered by animal and source."""
    conn = get_db()

    try:
        clauses = []
        params = []
        placeholder = "%s" if is_postgres() else "?"

        if animal_filter and animal_filter.lower() != "all":
            clauses.append("LOWER(animal) = LOWER(" + placeholder + ")")
            params.append(animal_filter)

        if source_filter and source_filter.lower() != "all":
            clauses.append("LOWER(source) = LOWER(" + placeholder + ")")
            params.append(source_filter)

        query = "SELECT * FROM detections"

        if clauses:
            query += " WHERE " + " AND ".join(clauses)

        query += " ORDER BY id DESC LIMIT " + placeholder
        params.append(max(1, int(limit)))

        with db_cursor(conn) as cur:
            cur.execute(query, params)
            return [dict(row) for row in cur.fetchall()]

    finally:
        conn.close()


def get_stats() -> dict:
    """Calculate statistics for the dashboard."""
    conn = get_db()

    try:
        with db_cursor(conn) as cur:
            cur.execute("""
                SELECT COUNT(*) AS cnt,
                       COALESCE(SUM(est_damage), 0) AS total_damage
                FROM detections
            """)

            totals = cur.fetchone()

            placeholder = "%s" if is_postgres() else "?"
            today = datetime.now().strftime("%Y-%m-%d")

            cur.execute(
                "SELECT COUNT(*) AS cnt FROM detections WHERE date = "
                + placeholder,
                (today,),
            )

            today_count = cur.fetchone()["cnt"]

            cur.execute("""
                SELECT animal, COUNT(*) AS cnt
                FROM detections
                GROUP BY animal
                ORDER BY cnt DESC
            """)

            animal_rows = cur.fetchall()

        return {
            "total_detections": totals["cnt"],
            "total_damage_inr": round(float(totals["total_damage"]), 2),
            "today_detections": today_count,
            "animal_counts": {
                row["animal"]: row["cnt"] for row in animal_rows
            },
            "top_animal": (
                animal_rows[0]["animal"] if animal_rows else "None"
            ),
        }

    finally:
        conn.close()


def get_alerts_since(since_id: int = 0, limit: int = 15) -> list:
    """Return detections whose IDs are greater than since_id."""
    conn = get_db()

    try:
        placeholder = "%s" if is_postgres() else "?"

        query = (
            "SELECT * FROM detections WHERE id > "
            + placeholder
            + " ORDER BY id ASC LIMIT "
            + placeholder
        )

        with db_cursor(conn) as cur:
            cur.execute(
                query,
                (max(0, int(since_id)), max(1, int(limit))),
            )
            return [dict(row) for row in cur.fetchall()]

    finally:
        conn.close()


def clear_history():
    """Delete all detections. Call only when intentionally clearing history."""
    conn = get_db()

    try:
        with db_cursor(conn) as cur:
            cur.execute("DELETE FROM detections")

        conn.commit()

    finally:
        conn.close()


